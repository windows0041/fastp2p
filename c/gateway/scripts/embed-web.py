#!/usr/bin/env python3
"""Embed a fixed asset allowlist, without runtime file-system web serving."""
from pathlib import Path
import sys

root, target = map(Path, sys.argv[1:])
assets = [('index.html', '/', 'text/html; charset=utf-8'),
          ('app.js', '/app.js', 'text/javascript; charset=utf-8'),
          ('style.css', '/style.css', 'text/css; charset=utf-8'),
          ('favicon.svg', '/favicon.svg', 'image/svg+xml')]
out = ['/* Generated by embed-web.py. */', '#include <stddef.h>',
       'struct web_asset { const char *path, *type; const unsigned char *data; size_t length; };']
for i, (name, _, _) in enumerate(assets):
    data = (root/name).read_bytes()
    assert 0 < len(data) < 512*1024, name
    out.append('static const unsigned char web_data_%d[] = {' % i)
    for start in range(0, len(data), 24):
        out.append(','.join(str(b) for b in data[start:start+24])+',')
    out.append('};')
out.append('static const struct web_asset web_assets[] = {')
for i, (_, path, kind) in enumerate(assets):
    out.append('{"%s","%s",web_data_%d,sizeof(web_data_%d)},' % (path, kind, i, i))
out.append('};')
target.write_text('\n'.join(out)+'\n', encoding='utf-8')
